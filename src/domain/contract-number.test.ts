import { describe, expect, it } from 'vitest';

import { formatContractNumber, nextContractNumber } from './contract-number';

/**
 * Номер договора (T8.1, указание владельца от 8 сентября 2026).
 *
 * Номер присваивает система, а не человек: вводимый руками номер рано или
 * поздно повторится, а договор с чужим номером — это спор, а не опечатка.
 * Нумерация сквозная в пределах сети и начинается заново каждый год —
 * так её и читают в договорах.
 */
describe('номер договора', () => {
  it('первый договор года получает первый номер', () => {
    expect(nextContractNumber(null, 2026)).toBe('2026-0001');
  });

  it('следующий продолжает нумерацию года', () => {
    expect(nextContractNumber('2026-0007', 2026)).toBe('2026-0008');
  });

  it('новый год начинает нумерацию заново', () => {
    expect(nextContractNumber('2025-0431', 2026)).toBe('2026-0001');
  });

  it('номер прошлого года не продолжается даже с большим счётчиком', () => {
    expect(nextContractNumber('2025-9999', 2026)).toBe('2026-0001');
  });

  it('непонятный номер нумерацию не ломает: считаем, что года ещё нет', () => {
    expect(nextContractNumber('без номера', 2026)).toBe('2026-0001');
    expect(nextContractNumber('', 2026)).toBe('2026-0001');
  });

  it('за пределами четырёх знаков номер растёт, а не обнуляется', () => {
    expect(nextContractNumber('2026-9999', 2026)).toBe('2026-10000');
    expect(formatContractNumber(2026, 12_345)).toBe('2026-12345');
  });

  it('формат виден сразу: год, дефис, четыре знака', () => {
    expect(formatContractNumber(2026, 1)).toBe('2026-0001');
    expect(formatContractNumber(2026, 42)).toBe('2026-0042');
  });
});
