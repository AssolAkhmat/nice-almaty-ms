'use client';

import type { ClipboardEvent, FocusEvent } from 'react';

import { formatPhone } from '@/domain/phone';

import { Input } from './input';

/** Что стоит в пустом поле до первого знака. */
export const PHONE_PREFIX = '+7 ';

/**
 * Поле телефона (отзыв жильца, 25 сентября 2026).
 *
 * Делает три вещи, которых не хватало:
 *
 * 1. Показывает `+7 ` в пустом поле, чтобы человек не гадал, с чего начинать.
 * 2. Вставку обрабатывает целиком: скопированный номер заменяет содержимое,
 *    а не приклеивается к уже набранному `+7` — ровно от этого получался
 *    мусор вида `+7+7 705…`.
 * 3. При уходе из поля показывает номер так, как его понял сервер:
 *    `+7 705 410 00 20`. Что не разобралось — остаётся как набрано,
 *    поле не должно молча портить непонятое.
 *
 * Разбирать номер здесь нечем и незачем: разбор один на всё приложение,
 * в `src/domain/phone.ts`, и отправляется на сервер исходная строка —
 * нормализацию всё равно делает он.
 *
 * ### Почему префикс — начальное значение, а не подстановка на фокусе
 *
 * Тот, кто заполняет поле не по одной букве, делает три шага в таком
 * порядке: выделяет содержимое, переводит фокус, вставляет текст поверх
 * выделения. Порядок именно такой — `input.select()` раньше `input.focus()`;
 * это не догадка, а код драйвера приёмки (`playwright-core`, `selectText`),
 * и так же устроено автозаполнение браузера.
 *
 * Значит подстановка на фокусе приходит **после** выделения: она его снимает
 * и уводит курсор в конец, вставка приклеивается к префиксу, получается
 * `+7 +77010000000`. Такое не разбирается, и человек читает «Неверный телефон
 * или пароль» на верном номере. Приёмке это стоило 305 упавших проверок,
 * жильцу стоило бы входа.
 *
 * Поэтому префикс стоит в разметке начальным значением: выделить и заменить
 * его можно, а перезаписывать под руками вставляющего нечего. Обработчика
 * фокуса здесь нет и быть не должно. При уходе из поля один префикс
 * стирается — иначе `required` перестал бы ловить незаполненное поле.
 *
 * Запрет держится проверкой `phone-input.test.ts`: и состояние, и `onFocus`
 * в этом файле её краснят, а заполнение повторяется в ней по шагам драйвера.
 */
export function PhoneInput({
  defaultValue = '',
  ...rest
}: Omit<React.ComponentProps<typeof Input>, 'onFocus' | 'onBlur' | 'onPaste' | 'value'>) {
  return (
    <Input
      {...rest}
      autoComplete="tel"
      defaultValue={defaultValue === '' ? PHONE_PREFIX : formatPhone(String(defaultValue))}
      inputMode="tel"
      onBlur={(event: FocusEvent<HTMLInputElement>) => {
        event.target.value = formatPhone(event.target.value).replace(/^\+7\s*$/, '');
      }}
      onPaste={(event: ClipboardEvent<HTMLInputElement>) => {
        event.preventDefault();
        event.currentTarget.value = formatPhone(event.clipboardData.getData('text'));
      }}
      placeholder="+7 700 000 00 00"
      type="tel"
    />
  );
}
