import { describe, expect, it } from 'vitest';

import { optionLabel, type PersonLabel } from './person-labels';

/**
 * Подпись в списке выбора не бывает пустой (разбор 28 сентября 2026).
 *
 * Экран счетов собрал список жильцов из пустых строк, и выбрать в нём было
 * нельзя никого: имена брались у владельцев счетов месяца, а список — из всех
 * действующих проживаний. Ни типы, ни `pnpm verify` этого не заметили —
 * пустая строка законна везде. Заметил прогон приёмок, через таймаут
 * «не нахожу вариант с таким названием».
 *
 * Поэтому правило теперь одно, в одном месте, и под проверкой.
 */
const label = (name: string | null, phone = '+77010000001'): PersonLabel => ({
  userId: 'u-1',
  name,
  phone,
});

describe('подпись человека в списке выбора', () => {
  it('имя, когда оно есть', () => {
    expect(optionLabel(label('Деньгин Тест'), 'запас')).toBe('Деньгин Тест');
  });

  it('телефон, когда профиль не заполнен', () => {
    expect(optionLabel(label(null), 'запас')).toBe('+77010000001');
  });

  it('телефон, когда имя из пробелов', () => {
    expect(optionLabel(label('   '), 'запас')).toBe('+77010000001');
  });

  it('запасное значение, когда подписи нет вовсе', () => {
    expect(optionLabel(undefined, 'запас')).toBe('запас');
  });

  it('запасное значение, когда пусты и имя, и телефон', () => {
    expect(optionLabel(label(null, '  '), 'запас')).toBe('запас');
  });

  /* Главное свойство: пустой подписи не бывает ни при каком состоянии данных. */
  it('никогда не отдаёт пустую строку', () => {
    const cases: (PersonLabel | undefined)[] = [
      undefined,
      label(null),
      label(''),
      label('   ', '   '),
      label(null, ''),
    ];

    for (const candidate of cases) {
      expect(optionLabel(candidate, 'запас')).not.toBe('');
    }
  });
});
