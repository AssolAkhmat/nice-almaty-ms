import { ROUTE_ACCESS, type RouteAccess } from './access-map';

import type { AccessRole } from '@/db/access';

/**
 * Таблица доступа для документации (находка P0-2, 27 сентября 2026).
 *
 * Документ собирается из карты, а не пишется руками: таблица, набранная
 * отдельно, разойдётся с кодом на первой же правке прав и будет врать
 * убедительнее, чем отсутствие таблицы. Тест сверяет файл с этой функцией.
 */
const ROLE_TITLES: Readonly<Record<AccessRole, string>> = {
  superadmin: 'суперадмин',
  admin: 'админ дома',
  resident: 'жилец',
};

function rolesOf(entry: RouteAccess): string {
  return (['superadmin', 'admin', 'resident'] as const)
    .filter((role) => entry.roles.includes(role))
    .map((role) => ROLE_TITLES[role])
    .join(', ');
}

export function renderAccessMatrix(entries: readonly RouteAccess[] = ROUTE_ACCESS): string {
  const rows = entries.map(
    (entry) =>
      `| \`${entry.route}\` | ${rolesOf(entry)} | ${
        entry.action === null ? 'вход без права' : `\`${entry.action}\``
      } | ${entry.target === 'self' ? 'про себя' : 'про дом'} | ${entry.why} |`,
  );

  return [
    '# 09. Матрица доступа к экранам',
    '',
    'Файл собран из `src/lib/access-map.ts` командой `pnpm access:matrix`.',
    'Править руками нечего: таблица, набранная отдельно от кода, разойдётся',
    'с ним на первой же правке прав. Расхождение ловит `src/lib/access-map.test.ts`.',
    '',
    'Заведено 27 сентября 2026 по находке P0-2: админ дома видел в меню раздел',
    'бухгалтерии. Роут отказывал, но список разделов не спрашивал прав вовсе.',
    '',
    'Колонка «чей объект» — про то, как экран спрашивает право. «Про себя» пускает',
    'жильца по области `self`; «про дом» спрашивает без своего идентификатора,',
    'иначе `user.read` открыл бы жильцу список жильцов дома.',
    '',
    '| Экран | Кому положен | Право | Чей объект | Почему |',
    '|---|---|---|---|---|',
    ...rows,
    '',
    '## Чего в этой таблице нет',
    '',
    'Обработчики `/api/v1` проверяют право сами: `assertApiAccess` со скоупом',
    'токена плюс проверка в сервисе. Скоуп токена уже нельзя расширить ролью',
    'выдавшего — это отдельное правило, и его держат фикстуры',
    '`src/app/api/v1/bot-api.db-test.ts`.',
    '',
    'Полномочия, которые сеть включает и выключает данными (D28), в таблице',
    'не отражены: они меняются в настройках, а не в коде. Экран, закрытый таким',
    'полномочием, объясняет отсутствие данных сам — в карте у него `вход без права`.',
    '',
  ].join('\n');
}
